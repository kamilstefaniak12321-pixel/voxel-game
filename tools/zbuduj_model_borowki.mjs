// Convert the supplied, data-only v1.2 meshes to one browser module.
// Run after editing assets/models/blueberry/borowka-*.mesh.json.
import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const root = new URL('../assets/models/blueberry/', import.meta.url);
const models = {};
for (const stage of ['young', 'empty', 'few', 'full']) {
    const mesh = JSON.parse(await readFile(new URL(`borowka-${stage}.mesh.json`, root), 'utf8'));
    assert.equal(mesh.unitsPerBlock, 16);
    assert.equal(mesh.stage, stage);
    models[stage] = mesh.parts.map(part => ({
        berry: part.category === 'berries',
        faces: part.faces.map(face => {
            assert.equal(face.v.length, 4);
            assert.equal(face.uv.length, 4);
            assert.ok(face.v.flat().every(Number.isFinite));
            assert.ok(face.uv.flat().every(v => Number.isFinite(v) && v >= 0 && v <= 64));
            return { v: face.v.map(v => v.map(n => n / 16)), uv: face.uv.map(uv => uv.map(n => n / 64)) };
        })
    }));
}
await writeFile(new URL('model-data.js', root),
    '// Generated by tools/zbuduj_model_borowki.mjs from the supplied v1.2 meshes.\n' +
    `export const BLUEBERRY_MODELS = ${JSON.stringify(models)};\n`);
