// ------------------------------------------------------------
// IMPORT KONCEPTU LIŚCI Z 8 CZĘŚCI (Blockbench, autor: Kamil)
//
// Blok liści = 8 sześcianików 8 x 8 x 8 pikseli (po jednym w każdej
// ósemce bloku), każdy obrócony o wielokrotność 90° wokół własnego
// punktu - na każdej ścianie wypada inna ćwiartka tekstury 16 x 16,
// a części lekko wystają albo chowają się względem siatki bloku.
// Importer piecze obroty i zapisuje:
//   assets/models/leaves/model-data.js - ściany części (wierzchołki
//       w blokach, 0-1 w komórce; UV 0-1) i środek każdej części
//       (punkt, wokół którego część się kołysze),
//   assets/textures/drzewa.png - region oryginalnej osadzonej tekstury.
// Animacja "lekki powiew" z pliku nie ma klatek kluczowych - ruch
// liczy shader liści (src/rendering/LeafParts.js).
//
//   node tools/import_liscie.mjs "ŚCIEŻKA/koncept na bardziej realistyczne liście.bbmodel"
// ------------------------------------------------------------
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { decodeTexturePng, writeTextureRegion } from './texture_regions.mjs';
import { createHash } from 'node:crypto';
import { basename } from 'node:path';

const sourcePath = process.argv[2];
if (!sourcePath) throw new Error('Podaj ścieżkę do konceptu liści .bbmodel.');
const sourceBytes = readFileSync(sourcePath);
const model = JSON.parse(sourceBytes.toString('utf8'));
const hash = (bytes) => createHash('sha256').update(bytes).digest('hex');

const texture = model.textures?.[0];
if (!texture || texture.width !== 16 || texture.height !== 16 || !texture.source?.startsWith('data:image/png;base64,')) {
    throw new Error('Oczekiwano osadzonej tekstury liści 16 × 16.');
}
const textureBytes = Buffer.from(texture.source.split(',')[1], 'base64');

const finite = (value, size) => Array.isArray(value) && value.length === size && value.every(Number.isFinite);
const clean = (n) => Math.abs(n) < 1e-10 ? 0 : Math.round(n * 1e8) / 1e8;

// Kolejność obrotów jak w Blockbench: X, potem Y, potem Z.
function rotate(point, angles = [0, 0, 0]) {
    let [x, y, z] = point;
    for (let axis = 0; axis < 3; axis++) {
        const angle = angles[axis] * Math.PI / 180, c = Math.cos(angle), s = Math.sin(angle);
        if (axis === 0) [y, z] = [y * c - z * s, y * s + z * c];
        if (axis === 1) [x, z] = [x * c + z * s, -x * s + z * c];
        if (axis === 2) [x, y] = [x * c - y * s, x * s + y * c];
    }
    return [x, y, z];
}

const parts = [];
for (const element of model.elements) {
    if (element.type !== 'mesh' || element.export === false || !finite(element.origin, 3)) continue;
    if (!finite(element.rotation ?? [0, 0, 0], 3) || (element.rotation ?? []).some((a) => a % 90 !== 0)) {
        throw new Error('Części liści obracane tylko o wielokrotności 90°.');
    }
    const world = (key) => {
        const local = element.vertices[key];
        if (!finite(local, 3)) throw new Error('Nieprawidłowy wierzchołek.');
        const p = rotate(local, element.rotation).map((n, i) => n + element.origin[i]);
        // Blok w Blockbench: x, z od -8 do 8, y od 0 do 16 -> komórka 0-1.
        return [clean(p[0] / 16 + 0.5), clean(p[1] / 16), clean(p[2] / 16 + 0.5)];
    };
    const faces = Object.values(element.faces).map((face) => {
        if (face.vertices.length !== 4) throw new Error('Ściany części muszą mieć 4 wierzchołki.');
        return {
            vertices: face.vertices.map(world),
            uv: face.vertices.map((key) => face.uv[key].map((n) => clean(n / 16)))
        };
    });
    const points = faces.flatMap((face) => face.vertices);
    const min = [0, 1, 2].map((i) => Math.min(...points.map((p) => p[i])));
    const max = [0, 1, 2].map((i) => Math.max(...points.map((p) => p[i])));
    parts.push({ center: min.map((n, i) => clean((n + max[i]) / 2)), min, max, faces });
}

if (parts.length !== 8 || parts.some((part) => part.faces.length !== 6)) {
    throw new Error(`Oczekiwano 8 części po 6 ścian (jest ${parts.length}).`);
}

const metadata = {
    source: basename(sourcePath), sourceSha256: hash(sourceBytes), textureSha256: hash(textureBytes),
    parts: parts.length, textureSize: [16, 16],
    bounds: [0, 1, 2].map((i) => [Math.min(...parts.map((p) => p.min[i])), Math.max(...parts.map((p) => p.max[i]))])
};

const output = new URL('../assets/models/leaves/', import.meta.url);
mkdirSync(output, { recursive: true });
writeTextureRegion(new URL('texture.png', output), decodeTexturePng(textureBytes));
writeFileSync(new URL('model-data.js', output),
    '// Generated by tools/import_liscie.mjs. One block = 16 source pixels, cell coordinates 0-1.\n' +
    '// Koncept Kamila: 8 części bloku liści, obroty wpieczone, UV oryginalne.\n' +
    `export const LEAF_PARTS_SOURCE = ${JSON.stringify(metadata, null, 2)};\n` +
    `export const LEAF_PARTS = ${JSON.stringify(parts.map(({ center, min, max, faces }) => ({ center, min, max, faces })))};\n`);
console.log(`Zaimportowano ${parts.length} części liści; granice ${JSON.stringify(metadata.bounds)}.`);
for (const p of parts) console.log(JSON.stringify(p.min), JSON.stringify(p.max));
