// Fixed built-in layer drawings: @ is the trunk origin, P is wood, L/l are
// solid/occasional foliage, and O is the apple-bearing leaf variant.
// No file discovery, network requests or optional tree packs at startup.
function template(source) {
    const layers = source.trim().split(/\n\s*\n/).map(layer => layer.split('\n'));
    const origins = layers[0].flatMap((row, z) => [...row].flatMap((cell, x) => cell === '@' ? [[x, z]] : []));
    if (origins.length !== 1) throw new Error('Tree template needs one trunk origin');
    const [ox, oz] = origins[0], cells = [];
    for (const [y, rows] of layers.entries()) for (const [z, row] of rows.entries()) {
        for (const [x, char] of [...row].entries()) {
            if (char === '.' || char === ' ') continue;
            if (!'@PLlO'.includes(char) || (char === '@' && y > 0) || y > 28 || Math.abs(x - ox) > 7 || Math.abs(z - oz) > 7) {
                throw new Error('Invalid built-in tree template cell');
            }
            cells.push([x - ox, y, z - oz, char]);
        }
    }
    return cells;
}

